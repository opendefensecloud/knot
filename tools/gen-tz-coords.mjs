// Builds web/src/lib/tzCoords.generated.ts, the table "Follow the sun" uses
// to place the browser's time zone, from an extracted tzdata release
// (https://data.iana.org/time-zones/releases/tzdataYYYYv.tar.gz):
//
//     node tools/gen-tz-coords.mjs <extracted-tzdata-dir>
//     make tz.gen TZDATA=<extracted-tzdata-dir>
//
// zone.tab gives each zone the coordinates of its principal city. `backward`
// adds the names zones were renamed or merged from, which browsers still
// report: Chrome follows ICU, which keeps `Asia/Calcutta` and `Europe/Kiev`.
// A few names ICU uses differently from `backward` are fixed by hand.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "web", "src", "lib", "tzCoords.generated.ts");

const tzdata = process.argv[2];
if (!tzdata) {
  console.error("usage: node tools/gen-tz-coords.mjs <extracted-tzdata-dir>");
  process.exit(2);
}

const read = (file) => readFileSync(join(tzdata, file), "utf8");

// zone.tab writes coordinates as ISO 6709 `±DDMM[SS]±DDDMM[SS]`.
const ISO6709 = /^([+-]\d{4}(?:\d{2})?)([+-]\d{5}(?:\d{2})?)$/;

// One signed `±D…DMM[SS]` half, with `width` degree digits, as decimal
// degrees rounded to 2 decimals (about 1 km). `+ 0` turns a -0 into 0.
function degrees(text, width) {
  const sign = text[0] === "-" ? -1 : 1;
  const d = Number(text.slice(1, 1 + width));
  const m = Number(text.slice(1 + width, 3 + width));
  const s = Number(text.slice(3 + width) || 0);
  return (sign * Math.round((d + m / 60 + s / 3600) * 100)) / 100 + 0;
}

// zone.tab's rows are `country<TAB>coordinates<TAB>zone[<TAB>comments]`.
const coords = new Map();
for (const line of read("zone.tab").split("\n")) {
  if (line === "" || line.startsWith("#")) continue;
  const [, at, zone] = line.split("\t");
  const match = ISO6709.exec(at);
  if (!match) throw new Error(`zone.tab: can't read coordinates ${at} of ${zone}`);
  coords.set(zone, [degrees(match[1], 2), degrees(match[2], 3)]);
}

// Link lines are `Link TARGET NAME`; the file also holds a few Zone and
// Rule lines, which name no coordinates. Because some parsers can't follow
// a link to a link, a few lines point at the final zone and keep the link
// they stand for in a `#= TARGET1` comment. TARGET1 is tried first, being
// the nearer place: ICU still reports Africa/Asmera, whose TARGET is
// Africa/Nairobi but whose TARGET1 is Africa/Asmara.
const links = new Map();
for (const line of read("backward").split("\n")) {
  const link = /^Link\s+(\S+)\s+(\S+)(?:\s+#=\s*(\S+))?/.exec(line);
  if (link) links.set(link[2], link[3] ? [link[3], link[1]] : [link[1]]);
}

// A name's coordinates are its own if zone.tab lists it, which it does for
// many merged zones (Africa/Accra is at Accra, not at Africa/Abidjan where
// its link points), else its first target's that has some, following links
// to links.
function locate(name, path = []) {
  if (coords.has(name)) return coords.get(name);
  if (path.includes(name)) throw new Error(`backward: link cycle ${[...path, name].join(" -> ")}`);
  for (const target of links.get(name) ?? []) {
    const at = locate(target, [...path, name]);
    if (at) return at;
  }
  return undefined;
}

const table = new Map(coords);
for (const name of links.keys()) {
  const at = locate(name);
  // Links into Etc/* have nowhere to point, and are left out.
  if (at) table.set(name, at);
}

// Names ICU reports for a zone whose `backward` link leads somewhere else,
// mapped to the zone they stand for, overriding the link. ICU keeps
// America/Coral_Harbour as the canonical name for Atikokan, Ontario, but
// `backward` links it to America/Panama, which would put a browser in
// Ontario at the Panama Canal. zone.tab lists Atikokan at +484531-0913718
// with the comment "ON (Atikokan), NU (Coral H)".
const ICU_ALIASES = { "America/Coral_Harbour": "America/Atikokan" };
for (const [alias, zone] of Object.entries(ICU_ALIASES)) {
  if (!coords.has(zone)) throw new Error(`zone.tab: no coordinates for ${zone}, which ${alias} stands for`);
  table.set(alias, coords.get(zone));
}

const version = read("version").trim();
// Sorted by UTF-16 code unit, so the order doesn't depend on the locale.
const names = [...table.keys()].sort();

writeFileSync(
  out,
  `// Code generated by tools/gen-tz-coords.mjs from tzdata ${version}. DO NOT EDIT.
// tzdata is in the public domain: https://www.iana.org/time-zones
// Regenerate with \`make tz.gen TZDATA=<extracted tzdata dir>\`.

export const TZDATA_VERSION = "${version}";

/** Each time zone's principal city as [lat, lon] in degrees, rounded to 2
 *  decimals: zone.tab's zones, and the backward link names that lead to one. */
export const TZ_COORDS: Readonly<Record<string, readonly [number, number]>> = {
${names.map((name) => `  ${JSON.stringify(name)}: [${table.get(name).join(", ")}],`).join("\n")}
};
`,
);
console.log(`${relative(root, out)}  ${names.length} zones, tzdata ${version}`);
